#include<iostream>
using namespace std;
int main(){
    //Do-while loop runs minimum 1 times
    int i =11;
    do{
        cout<<i<<" ";
        i++;
    }
    while(i<=10);

    // in Do-while loop initialization takes place befire then statement & inc/decrement is written in do{} block and condition is written in while() after which semicolon ; is necessary

    //Such type of loop runs at least one time even if condition is false because the condition is written after the statement
}