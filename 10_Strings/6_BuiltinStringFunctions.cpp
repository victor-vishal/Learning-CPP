// Built-in string functions are pre-defined operations provided by programming languages or database systems to manipulate and process text data. These functions streamline common tasks related to strings, such as extracting parts of a string, modifying its case, searching for substrings, or combining strings.
// Common Categories of Built-in String Functions:
// Length and Size:
// length() or size(): Returns the number of characters in a string. 
// Accessing Characters:
// Indexing (e.g., string[index]): Accesses individual characters at a specific position.
// charAt() or at(): Returns the character at a given index.
// Concatenation and Appending:
// + operator: Combines two or more strings.
// concat() or append(): Adds one string to the end of another. 
// Case Conversion:
// toLowerCase() or lower(): Converts all characters to lowercase.
// toUpperCase() or upper(): Converts all characters to uppercase.
// capitalize(): Capitalizes the first letter of a string.
// Substrings:
// substring() or substr(): Extracts a portion of a string based on starting position and length.
// slice(): Extracts a part of a string and returns a new string. 
// Searching and Finding:
// find() or indexOf(): Returns the starting position of the first occurrence of a substring. 
// lastIndexOf() or rfind(): Returns the starting position of the last occurrence of a substring.
// startsWith(): Checks if a string begins with specified characters.
// endsWith(): Checks if a string ends with specified characters.
// Comparison:
// == operator or equals(): Compares two strings for equality.
// compare() or strcmp(): Compares two strings lexicographically.
// Modification:
// replace(): Replaces occurrences of a substring with another.
// insert(): Adds a substring at a specified position.
// erase(): Removes a part of a string.
// trim() or strip(): Removes leading/trailing whitespace or specified characters.
// Examples in Different Languages:
// Python: len("hello"), "hello".upper(), "hello world".find("world")
// JavaScript: "hello".length, "hello".toUpperCase(), "hello world".indexOf("world")
// C++: myString.length(), myString.substr(0, 5), myString.replace(0, 5, "hi")
// SQL: LENGTH(column_name), UPPER(column_name), SUBSTRING(column_name, 1, 5)